//! Input extractors for the §24.1 validator.
//!
//! Each function takes the *concatenated* source text of one input class
//! (Rust command registry, generated TypeScript, SQLite schema, Zustand
//! store interfaces, Stitch screen manifest) and returns the identifiers
//! that class declares. The extractors are deliberately conservative: they
//! recognise only the documented forms and ignore everything else, so a
//! drift in formatting is reported as "absent", never as a spurious match.
//!
//! None of these extractors are speculatively tolerant — that would defeat
//! the §24.1 fail-loud contract. They look for one canonical pattern per
//! input class.

use std::collections::BTreeMap;

/// Extract Tauri command names from a Rust command registry source.
///
/// Recognised form (the only form `tauri::Builder::invoke_handler` accepts):
///
/// ```text
/// #[tauri::command]
/// pub fn home_snapshot(/* … */) -> … { … }
/// #[tauri::command]
/// pub async fn job_list(/* … */) -> … { … }
/// ```
///
/// The function name following the attribute is the command name. A custom
/// `rename_all`/`name` on the macro is intentionally not honoured — the
/// application contract requires the Rust function name to equal the
/// Tauri command name (§14.4), so recognising only that form catches drift.
pub fn extract_rust_commands(src: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut pending = false;
    for raw in src.lines() {
        let line = raw.trim_start();
        if line.starts_with("#[tauri::command") {
            pending = true;
            continue;
        }
        if pending {
            if let Some(name) = parse_pub_fn_name(line) {
                out.push(name.to_string());
                pending = false;
                continue;
            }
            // An attribute is pending only until the next item line; if the
            // next non-blank line is not a fn declaration, the pending
            // attribute was attached to something we do not care about
            // (struct, impl, etc.) and should not bleed forward.
            if !line.is_empty() && !line.starts_with("//") && !line.starts_with("#[") {
                pending = false;
            }
        }
    }
    out
}

fn parse_pub_fn_name(line: &str) -> Option<&str> {
    let rest = line
        .strip_prefix("pub async fn ")
        .or_else(|| line.strip_prefix("pub fn "))?;
    take_ident(rest)
}

fn take_ident(s: &str) -> Option<&str> {
    let bytes = s.as_bytes();
    if bytes.is_empty() {
        return None;
    }
    if !bytes[0].is_ascii_alphabetic() && bytes[0] != b'_' {
        return None;
    }
    let end = bytes
        .iter()
        .position(|b| !(b.is_ascii_alphanumeric() || *b == b'_'))
        .unwrap_or(bytes.len());
    if end == 0 {
        return None;
    }
    Some(&s[..end])
}

/// Extract exported TypeScript identifier names from a generated entities
/// source. Recognises the forms produced by `tools/contract-gen` (§14.4):
///
/// ```text
/// export interface Foo { … }
/// export type Foo = … ;
/// export enum Foo { … }
/// export class Foo { … }
/// export const Foo = … ;
/// ```
///
/// `export const` is included because some §24 entities (e.g. enum-like
/// unions frozen as const objects) are emitted as `export const`. Only
/// the identifier at the immediate `export <kind>` position is captured —
/// destructuring `export const { a, b }` is not generated by this pipeline
/// and would be a contract violation to introduce.
pub fn extract_ts_entities(src: &str) -> Vec<String> {
    let mut out = Vec::new();
    for raw in src.lines() {
        let line = raw.trim_start();
        for prefix in [
            "export interface ",
            "export type ",
            "export enum ",
            "export class ",
            "export const ",
        ] {
            if let Some(rest) = line.strip_prefix(prefix) {
                if let Some(name) = take_ident(rest) {
                    out.push(name.to_string());
                }
                break;
            }
        }
    }
    out
}

/// Extract `CREATE TABLE` names from a SQLite schema source.
///
/// Recognises both `CREATE TABLE name (` and
/// `CREATE TABLE IF NOT EXISTS name (` (§6.2 uses the latter for the
/// initial migration). The name may be backtick-quoted per the §6.2
/// style; backticks are stripped from the captured identifier.
pub fn extract_sql_tables(src: &str) -> Vec<String> {
    let mut out = Vec::new();
    for raw in src.lines() {
        let line = raw.trim_start();
        let after_create = if let Some(rest) = line.strip_prefix("CREATE TABLE ") {
            rest
        } else {
            continue;
        };
        let after_create = after_create.trim_start();
        let after_create =
            after_create.strip_prefix("IF NOT EXISTS ").unwrap_or(after_create);
        let after_create = after_create.trim_start();
        let name_with_rest = match after_create.strip_prefix('`') {
            Some(s) => s.split('`').next().unwrap_or(""),
            None => take_ident(after_create).unwrap_or(""),
        };
        if !name_with_rest.is_empty() {
            out.push(name_with_rest.to_string());
        }
    }
    out
}

/// One Zustand store's public interface as observed by the validator.
///
/// `top_level_keys` are the immediate keys returned by the store's `create`
/// factory — these are what §24 calls a "slice". Nested keys (e.g.
/// `snapshot.continueReading`) are not flattened; the validator walks the
/// dotted store path one segment at a time.
#[derive(Clone, Debug, Default)]
pub struct StoreInterface {
    pub store_name: String,
    pub top_level_keys: Vec<String>,
}

/// Extract Zustand store interfaces from a TypeScript store source.
///
/// Recognised form (the canonical Zustand v4+ pattern):
///
/// ```text
/// export const homeStore = create<HomeState>()((set, get) => ({
///   snapshot: { continueReading: [], recentPacks: [] },
///   catalogQuery: null,
/// }));
/// ```
///
/// The store name is captured verbatim so the §24 store_slice
/// `homeStore.snapshot` resolves to the same identifier. Only top-level
/// keys of the object literal the `create` factory returns are captured;
/// nested keys are not flattened because §24 binding paths already walk
/// them segment by segment.
///
/// Depth is tracked across lines in a single character sweep, so a
/// multi-line nested object on lines that follow the `{` does not bleed
/// its inner keys into the top-level set.
///
/// If the source contains no `create<…>()` factories (for example because
/// the UI has not been authored yet), the returned vector is empty and the
/// validator reports each §24 store_slice as missing rather than guessing.
pub fn extract_store_interfaces(src: &str) -> Vec<StoreInterface> {
    let mut out = Vec::new();
    let bytes = src.as_bytes();
    let mut cursor = 0usize;
    while cursor < bytes.len() {
        let anchor = match find_substring(bytes, cursor, b"export const ") {
            Some(idx) => idx,
            None => break,
        };
        let after_kw = anchor + b"export const ".len();
        let name_end = match ident_end(bytes, after_kw) {
            Some(end) => end,
            None => {
                cursor = after_kw;
                continue;
            }
        };
        let store_name = &src[after_kw..name_end];
        // Skip whitespace.
        let mut p = name_end;
        while p < bytes.len() && (bytes[p] == b' ' || bytes[p] == b'\t') {
            p += 1;
        }
        if p >= bytes.len() || bytes[p] != b'=' {
            cursor = name_end;
            continue;
        }
        p += 1;
        while p < bytes.len() && (bytes[p] == b' ' || bytes[p] == b'\t') {
            p += 1;
        }
        // Expect the literal identifier `create`.
        if &src[p..(p + 6).min(src.len())] != "create" {
            cursor = name_end;
            continue;
        }
        p += 6;
        // Scan forward to the first top-level `{` that begins the object
        // literal returned by the factory. This accepts both
        // `create<T>()((set, get) => ({ … }))` and
        // `create<T>((set, get) => ({ … }))` and tolerates the body
        // spanning many lines. We do not interpret generics or arg lists:
        // the first `{` whose matching `}` is the end of an expression
        // statement at the depth where `=>` lives is the object literal.
        // The Zustand factory always returns the object literal directly,
        // so the first `{` after the arrow is the one we want.
        let arrow_pos = match find_substring(bytes, p, b"=>") {
            Some(idx) => idx,
            None => {
                cursor = p;
                continue;
            }
        };
        let mut obj_start = None;
        let mut q = arrow_pos + 2;
        while q < bytes.len() {
            let c = bytes[q];
            if c == b'{' {
                obj_start = Some(q);
                break;
            }
            if !c.is_ascii_whitespace() && c != b'(' {
                // The arrow does not return an object literal directly
                // (e.g. `=> { return …; }`). The §24 store contract is
                // the direct object form; do not guess.
                break;
            }
            q += 1;
        }
        let obj_start = match obj_start {
            Some(s) => s,
            None => {
                cursor = arrow_pos + 2;
                continue;
            }
        };
        let (keys, obj_end) = scan_top_level_keys(src, obj_start);
        out.push(StoreInterface {
            store_name: store_name.to_string(),
            top_level_keys: keys,
        });
        cursor = obj_end.saturating_add(1);
    }
    out
}

/// Sweep the object literal that begins at `obj_start` (the index of the
/// opening `{` in `src`) and return every top-level object key plus the
/// index of the matching closing `}`. Depth is tracked across the entire
/// literal so nested multi-line objects do not promote inner keys.
fn scan_top_level_keys(src: &str, obj_start: usize) -> (Vec<String>, usize) {
    let bytes = src.as_bytes();
    let mut keys = Vec::new();
    let mut depth: i32 = 0;
    let mut i = obj_start;
    let mut in_string: Option<u8> = None;
    while i < bytes.len() {
        let c = bytes[i];
        if let Some(quote) = in_string {
            if c == quote {
                in_string = None;
            } else if c == b'\\' && i + 1 < bytes.len() {
                i += 1;
            }
            i += 1;
            continue;
        }
        match c {
            b'"' | b'\'' | b'`' => {
                in_string = Some(c);
            }
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return (keys, i);
                }
            }
            _ if depth == 1 && (c.is_ascii_alphabetic() || c == b'_') => {
                let ident_end = ident_end(bytes, i).unwrap_or(i);
                // Skip whitespace.
                let mut scan = ident_end;
                while scan < bytes.len()
                    && (bytes[scan] == b' ' || bytes[scan] == b'\t')
                {
                    scan += 1;
                }
                if scan < bytes.len()
                    && (bytes[scan] == b':' || bytes[scan] == b'(')
                {
                    keys.push(src[i..ident_end].to_string());
                }
                i = ident_end;
                continue;
            }
            _ => {}
        }
        i += 1;
    }
    (keys, bytes.len())
}

fn find_substring(haystack: &[u8], from: usize, needle: &[u8]) -> Option<usize> {
    if needle.is_empty() || from >= haystack.len() {
        return None;
    }
    haystack[from..]
        .windows(needle.len())
        .position(|w| w == needle)
        .map(|p| p + from)
}

fn ident_end(bytes: &[u8], start: usize) -> Option<usize> {
    if start >= bytes.len() {
        return None;
    }
    if !(bytes[start].is_ascii_alphabetic() || bytes[start] == b'_') {
        return None;
    }
    let mut end = start;
    while end < bytes.len()
        && (bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_')
    {
        end += 1;
    }
    Some(end)
}

/// Coalesce a slice of [`StoreInterface`] into a name → interface map. When
/// the same store name is declared more than once, later declarations win —
/// matching JavaScript module semantics where the last `export const` of a
/// given name shadows earlier ones at link time.
pub fn store_map(stores: &[StoreInterface]) -> BTreeMap<&str, &StoreInterface> {
    let mut map = BTreeMap::new();
    for s in stores {
        map.insert(s.store_name.as_str(), s);
    }
    map
}

#[cfg(test)]
mod extract_tests {
    use super::*;

    #[test]
    fn rust_commands_basic() {
        let src = r#"
            #[tauri::command]
            pub fn home_snapshot() -> u32 { 0 }

            #[tauri::command]
            pub async fn job_list() -> Vec<u8> { vec![] }

            // not a command:
            pub fn helper() {}

            #[tauri::command]
            pub async fn pack_list() -> Vec<u8> { vec![] }
        "#;
        let got = extract_rust_commands(src);
        assert_eq!(got, vec!["home_snapshot", "job_list", "pack_list"]);
    }

    #[test]
    fn rust_commands_attribute_on_non_fn_does_not_leak() {
        let src = r#"
            // an attribute that is NOT a tauri command, but formatted similarly
            #[some::other::command]
            pub fn not_a_command() {}
            #[tauri::command]
            pub fn real_command() {}
        "#;
        let got = extract_rust_commands(src);
        assert_eq!(got, vec!["real_command"]);
    }

    #[test]
    fn ts_entities_all_kinds() {
        let src = r#"
            export interface HomeSnapshot { count: number; }
            export type PackManifest = { id: string; };
            export enum Capability { On, Off }
            export class Foo { bar(): void {} }
            export const MemoryInboxCount = 0;
            // not exported:
            type Internal = string;
        "#;
        let mut got = extract_ts_entities(src);
        got.sort();
        assert_eq!(
            got,
            vec!["Capability", "Foo", "HomeSnapshot", "MemoryInboxCount", "PackManifest"]
        );
    }

    #[test]
    fn sql_tables_with_and_without_if_not_exists() {
        let src = r#"
            CREATE TABLE schema_migrations (
                version INTEGER NOT NULL PRIMARY KEY
            );
            CREATE TABLE IF NOT EXISTS packs (
                id TEXT NOT NULL PRIMARY KEY
            );
            CREATE TABLE IF NOT EXISTS `app_meta` (
                key TEXT NOT NULL PRIMARY KEY
            );
            -- comment, ignored
        "#;
        let mut got = extract_sql_tables(src);
        got.sort();
        assert_eq!(got, vec!["app_meta", "packs", "schema_migrations"]);
    }

    #[test]
    fn store_interfaces_top_level_keys() {
        let src = r#"
            export const homeStore = create<HomeState>()((set, get) => ({
                snapshot: { continueReading: [], recentPacks: [] },
                catalogQuery: null,
                readiness: null,
            }));

            export const libraryStore = create<LibraryState>((set) => ({
                packs: [],
                downloads: [],
            }));
        "#;
        let stores = extract_store_interfaces(src);
        assert_eq!(stores.len(), 2);
        let home = stores.iter().find(|s| s.store_name == "homeStore").unwrap();
        let mut home_keys = home.top_level_keys.clone();
        home_keys.sort();
        assert_eq!(home_keys, vec!["catalogQuery", "readiness", "snapshot"]);
        let library = stores
            .iter()
            .find(|s| s.store_name == "libraryStore")
            .unwrap();
        let mut lib_keys = library.top_level_keys.clone();
        lib_keys.sort();
        assert_eq!(lib_keys, vec!["downloads", "packs"]);
    }

    #[test]
    fn store_interfaces_empty_when_no_create() {
        let src = "export const notAStore = 42;";
        assert!(extract_store_interfaces(src).is_empty());
    }
}
